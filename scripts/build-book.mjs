// Builds index.html: a browsable book of the design system (README, templates, every
// @dsCard card), close to what Claude Design shows. Served by GitHub Pages and `npm run serve`.
// Usage: node scripts/build-book.mjs [--check]
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = 'index.html';

// Groups in the order Claude Design lists them; unknown groups follow alphabetically.
const GROUP_ORDER = ['Templates', 'Brand', 'Colors', 'Type', 'Spacing', 'Components · Core', 'Components · Cards', 'Components · Content', 'Components · Forms', 'Components · Layout', 'Website'];

const attrs = (line) => Object.fromEntries([...line.matchAll(/(\w+)="([^"]*)"/g)].map((m) => [m[1], m[2]]));

function collect() {
  const files = execFileSync('git', ['ls-files', '*.html'], { cwd: ROOT, encoding: 'utf8' }).split('\n').filter(Boolean);
  const items = [];
  for (const path of files) {
    const source = readFileSync(join(ROOT, path), 'utf8');
    const card = source.split('\n', 1)[0].match(/<!--\s*@dsCard\b(.*?)-->/);
    if (card) {
      const { group, name, subtitle = '', viewport = '800x600' } = attrs(card[1]);
      const [width, height] = viewport.split('x').map(Number);
      items.push({ group, name, subtitle, path, kind: 'card', width, height });
      continue;
    }
    const template = source.match(/<!--\s*@template\b(.*?)-->/);
    if (template) {
      const { name, description = '' } = attrs(template[1]);
      items.push({ group: 'Templates', name, subtitle: description, path, kind: 'template' });
    }
  }
  const rank = (group) => (GROUP_ORDER.includes(group) ? GROUP_ORDER.indexOf(group) : GROUP_ORDER.length);
  const groups = [...new Set(items.map((i) => i.group))].sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  return groups.map((group) => ({
    group,
    items: items.filter((i) => i.group === group).sort((a, b) => a.name.localeCompare(b.name, 'pl')),
  }));
}

